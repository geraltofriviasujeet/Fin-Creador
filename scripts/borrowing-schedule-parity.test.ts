import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { type BorrowingReturnPlan, borrowingSchedule } from "../packages/domain/src/borrowing";

// Parity fixture for borrowing return plans: borrowingSchedule in packages/domain, checked by
// pgTAP against public.borrowing_schedule (create_borrowing and set_borrowing_return_plan build
// the due items with it). Regenerate after changing either side: `npm run fixtures:borrowing`.

const SQL_PATH = fileURLToPath(new URL("../supabase/tests/database/borrowing_schedule_parity.test.sql", import.meta.url));

type Case = { id: number; totalMinor: number; borrowedMinor: number; returnOn: string; returnPlan: BorrowingReturnPlan; instalmentCount: number | null };

/** Two years of months across a common and a leap February (2027, 2028), on days around month ends. */
const DATES = Array.from({ length: 24 }, (_, i) => `${2027 + Math.floor(i / 12)}-${String((i % 12) + 1).padStart(2, "0")}`).flatMap((m) =>
  ["01", "15", "28", "29", "30", "31"].map((d) => `${m}-${d}`).filter((d) => !Number.isNaN(Date.parse(`${d}T00:00:00Z`)) && new Date(`${d}T00:00:00Z`).toISOString().startsWith(d)),
);
/** Amounts: none extra, some extra, extra most of the total, odd remainders, the maximum. */
const AMOUNTS: [number, number][] = [[100, 100], [100000, 90000], [12, 1], [1_000_003, 7], [999, 998], [10_000_000_000_000, 1]];
const COUNTS = [2, 3, 7, 12, 13, 60];

function generateCases(): Case[] {
  const cases: Omit<Case, "id">[] = [
    ...DATES.flatMap((returnOn) => [
      { totalMinor: 110000, borrowedMinor: 100000, returnOn, returnPlan: "once" as const, instalmentCount: null },
      ...[2, 13].map((n) => ({ totalMinor: 100000, borrowedMinor: 90000, returnOn, returnPlan: "instalments" as const, instalmentCount: n })),
    ]),
    ...AMOUNTS.flatMap(([totalMinor, borrowedMinor]) =>
      COUNTS.filter((n) => n <= totalMinor).map((n) => ({ totalMinor, borrowedMinor, returnOn: "2027-08-31", returnPlan: "instalments" as const, instalmentCount: n })),
    ),
  ];
  return cases.map((c, id) => ({ ...c, id }));
}

function generateSql(cases: Case[]): string {
  const caseRows = cases
    .map((c, i) => `  (${c.id}${i === 0 ? "::integer" : ""}, ${c.totalMinor}${i === 0 ? "::bigint" : ""}, ${c.borrowedMinor}${i === 0 ? "::bigint" : ""}, date '${c.returnOn}', '${c.returnPlan}', ${c.instalmentCount ?? "null"}${i === 0 ? "::integer" : ""})`)
    .join(",\n");
  const items = cases.flatMap((c) => borrowingSchedule(c).map((s) => ({ id: c.id, ...s })));
  const itemRows = items
    .map((s, i) => `  (${s.id}${i === 0 ? "::integer" : ""}, ${s.seq}${i === 0 ? "::integer" : ""}, date '${s.dueDate}', ${s.amountMinor}${i === 0 ? "::bigint" : ""}, ${s.interestMinor}${i === 0 ? "::bigint" : ""})`)
    .join(",\n");
  const mismatches = `$$ select coalesce(a.id, e.id), coalesce(a.seq, e.seq)
     from (select c.id, s.* from cases as c
           cross join lateral public.borrowing_schedule(c.total_minor, c.total_minor - c.borrowed_minor, c.return_on, c.return_plan, c.instalment_count) as s) as a
     full join expected as e on e.id = a.id and e.seq = a.seq
     where (a.due_date, a.amount_minor, a.interest_minor) is distinct from (e.due_date, e.amount_minor, e.interest_minor) $$`;
  return `-- GENERATED by scripts/borrowing-schedule-parity.test.ts from packages/domain/src/borrowing.ts.
-- Do not edit: run \`npm run fixtures:borrowing\`. ${cases.length} plans, ${items.length} due items.
-- public.borrowing_schedule (migration 20261028210000) must match the domain for every plan
-- (month ends, February, a leap year, odd remainders, the maximum amount), in any session time zone.
begin;
create extension if not exists pgtap with schema extensions;

select plan(3);

create temporary table cases (id integer, total_minor bigint, borrowed_minor bigint, return_on date, return_plan text, instalment_count integer) on commit drop;
insert into cases values
${caseRows};

create temporary table expected (id integer, seq integer, due_date date, amount_minor bigint, interest_minor bigint) on commit drop;
insert into expected values
${itemRows};

select is_empty(${mismatches},
  'borrowing schedules match packages/domain (${cases.length} plans)');

set local timezone = 'Pacific/Kiritimati';
select is_empty(${mismatches},
  'and with the session time zone at UTC+14');

set local timezone = 'Pacific/Pago_Pago';
select is_empty(${mismatches},
  'and with the session time zone at UTC-11');

select * from finish();
rollback;
`;
}

describe("borrowing schedule parity fixture", () => {
  const cases = generateCases();
  if (process.env.BORROWING_FIXTURE === "write") writeFileSync(SQL_PATH, generateSql(cases));

  it("covers month ends, February and a leap year", () => {
    expect(DATES).toContain("2027-01-31");
    expect(DATES).toContain("2028-02-29");
    expect(DATES).not.toContain("2027-02-29");
    expect(DATES).not.toContain("2027-04-31");
  });

  it("the pgTAP file is up to date (run `npm run fixtures:borrowing`)", () => {
    expect(readFileSync(SQL_PATH, "utf8")).toBe(generateSql(cases));
  });
});
