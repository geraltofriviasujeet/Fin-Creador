import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { beforeTrackingDate, instalmentDate, moratoriumDates } from "../packages/domain/src/loans";

// Parity fixture for loan due dates: the dates packages/domain gives (instalmentDate,
// beforeTrackingDate, moratoriumDates), checked by pgTAP against public.loan_due_date, which
// create_loan uses for every EMI, EMI 0 (paid before tracking) and moratorium month.
// Regenerate after changing either side: `npm run fixtures:loans`.

const SQL_PATH = fileURLToPath(new URL("../supabase/tests/database/loan_dates_parity.test.sql", import.meta.url));

/** 29th, 30th and 31st starts, February in common and leap years, a leap-day start. */
const FIRSTS = ["2027-01-29", "2027-01-30", "2027-01-31", "2027-03-31", "2027-11-30", "2028-02-29"];
const MORATORIUM = 12;
const MAX_EMIS = 480;

type Case = { first: string; seq: number; expected: string };

function generateCases(): Case[] {
  return FIRSTS.flatMap((first) => {
    // Moratorium month m of 12 is seq m − 12 (−11..0); seq 0 is also this month's EMI paid before tracking.
    const moratorium = moratoriumDates(first, MORATORIUM).map((expected, i) => ({ first, seq: i + 1 - MORATORIUM, expected }));
    const emis = Array.from({ length: MAX_EMIS }, (_, i) => ({ first, seq: i + 1, expected: instalmentDate(first, i + 1) }));
    return [...moratorium, ...emis];
  });
}

function generateSql(cases: Case[]): string {
  const rows = cases.map((c, i) => `  (date '${c.first}', ${c.seq}${i === 0 ? "::integer" : ""}, date '${c.expected}')`).join(",\n");
  const mismatches = `$$ select c.first_due, c.seq, c.expected from parity as c
     where public.loan_due_date(c.first_due, c.seq) is distinct from c.expected $$`;
  return `-- GENERATED by scripts/loan-dates-parity.test.ts from packages/domain/src/loans.ts.
-- Do not edit: run \`npm run fixtures:loans\`. ${cases.length} cases.
-- public.loan_due_date (migration 20261028120000) gives every EMI, EMI 0 and moratorium
-- date create_loan stores; it must match the domain for every case, in any session time zone.
begin;
create extension if not exists pgtap with schema extensions;

select plan(3);

create temporary table parity (first_due date, seq integer, expected date) on commit drop;
insert into parity values
${rows};

select is_empty(${mismatches},
  'loan_due_date matches packages/domain (${cases.length} cases)');

set local timezone = 'Pacific/Kiritimati';
select is_empty(${mismatches},
  'and with the session time zone at UTC+14');

set local timezone = 'Pacific/Pago_Pago';
select is_empty(${mismatches},
  'and with the session time zone at UTC-11');

select * from finish();
rollback;
`;
}

describe("loan due-date parity fixture", () => {
  const cases = generateCases();
  if (process.env.LOAN_DATES_FIXTURE === "write") writeFileSync(SQL_PATH, generateSql(cases));

  it("covers month ends, February, a leap year, 1 and 480 EMIs and the moratorium months", () => {
    const at = (first: string, seq: number) => cases.find((c) => c.first === first && c.seq === seq)?.expected;
    expect(at("2027-01-31", 1)).toBe("2027-01-31"); // a 1-month loan is the first date
    expect(at("2027-01-31", 2)).toBe("2027-02-28");
    expect(at("2027-01-31", 3)).toBe("2027-03-31");
    expect(at("2027-11-30", 4)).toBe("2028-02-29"); // leap year
    expect(at("2028-02-29", 13)).toBe("2029-02-28");
    expect(at("2027-01-29", MAX_EMIS)).toBe("2066-12-29");
    expect(at("2027-03-31", 0)).toBe("2027-02-28");
    expect(at("2027-03-31", 0)).toBe(beforeTrackingDate("2027-03-31", true)); // EMI 0 = before tracking
    expect(at("2027-01-31", -11)).toBe("2026-01-31");
  });

  it("the pgTAP file is up to date (run `npm run fixtures:loans`)", () => {
    expect(readFileSync(SQL_PATH, "utf8")).toBe(generateSql(cases));
  });
});
