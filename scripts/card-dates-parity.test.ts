import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { cardCycleDate, cardDueDate } from "../packages/domain/src/cards";

// Parity fixture for card dates: cardCycleDate and cardDueDate in packages/domain, checked by
// pgTAP against public.card_cycle_date and public.card_due_date (enter_card_statement uses the
// latter when no due date is given). Regenerate after changing either side:
// `npm run fixtures:cards`.

const SQL_PATH = fileURLToPath(new URL("../supabase/tests/database/card_dates_parity.test.sql", import.meta.url));

/** Two years of months across a common and a leap February (2027, 2028). */
const MONTHS = Array.from({ length: 24 }, (_, i) => `${2027 + Math.floor(i / 12)}-${String((i % 12) + 1).padStart(2, "0")}-01`);
const DAYS = Array.from({ length: 31 }, (_, i) => i + 1);
/** Statement and due days around month ends and either side of each other. */
const PAIRS: [number, number][] = [
  [1, 20], [5, 25], [15, 5], [20, 8], [20, 20], [25, 15], [28, 18], [29, 30], [30, 29], [30, 31], [31, 30], [31, 1], [31, 31],
];

type CycleCase = { day: number; month: string; expected: string };
type DueCase = { statementDate: string; dueDay: number; expected: string };

function generateCases(): { cycle: CycleCase[]; due: DueCase[] } {
  const cycle = MONTHS.flatMap((month) => DAYS.map((day) => ({ day, month, expected: cardCycleDate(day, month) })));
  // Statements on their statement day, and on every day of the month (entered late).
  const onDay = MONTHS.flatMap((month) =>
    PAIRS.map(([statementDay, dueDay]) => {
      const statementDate = cardCycleDate(statementDay, month);
      return { statementDate, dueDay, expected: cardDueDate(statementDate, dueDay) };
    }),
  );
  const anyDay = MONTHS.slice(0, 14).flatMap((month) =>
    DAYS.map((day) => cardCycleDate(day, month)).filter((d, i, all) => all.indexOf(d) === i)
      .flatMap((statementDate) => [1, 15, 28, 30, 31].map((dueDay) => ({ statementDate, dueDay, expected: cardDueDate(statementDate, dueDay) }))),
  );
  const due = [...onDay, ...anyDay];
  return { cycle, due };
}

function generateSql({ cycle, due }: ReturnType<typeof generateCases>): string {
  const cycleRows = cycle.map((c, i) => `  (${c.day}${i === 0 ? "::integer" : ""}, date '${c.month}', date '${c.expected}')`).join(",\n");
  const dueRows = due
    .map((c, i) => `  (date '${c.statementDate}', ${c.dueDay}${i === 0 ? "::integer" : ""}, date '${c.expected}')`)
    .join(",\n");
  const mismatches = `$$ select c.day, c.month, c.expected from cycle as c
     where public.card_cycle_date(c.day, c.month) is distinct from c.expected
     union all
     select d.due_day, d.statement_date, d.expected from due as d
     where public.card_due_date(d.statement_date, d.due_day) is distinct from d.expected $$`;
  const total = cycle.length + due.length;
  return `-- GENERATED by scripts/card-dates-parity.test.ts from packages/domain/src/cards.ts.
-- Do not edit: run \`npm run fixtures:cards\`. ${total} cases.
-- public.card_cycle_date and public.card_due_date (migration 20261028180000) must match the
-- domain for every case (29th to 31st, February, a leap year), in any session time zone.
begin;
create extension if not exists pgtap with schema extensions;

select plan(3);

create temporary table cycle (day integer, month date, expected date) on commit drop;
insert into cycle values
${cycleRows};

create temporary table due (statement_date date, due_day integer, expected date) on commit drop;
insert into due values
${dueRows};

select is_empty(${mismatches},
  'card dates match packages/domain (${total} cases)');

set local timezone = 'Pacific/Kiritimati';
select is_empty(${mismatches},
  'and with the session time zone at UTC+14');

set local timezone = 'Pacific/Pago_Pago';
select is_empty(${mismatches},
  'and with the session time zone at UTC-11');

select * from finish();
rollback;
`;
}

describe("card dates parity fixture", () => {
  const cases = generateCases();
  if (process.env.CARD_DATES_FIXTURE === "write") writeFileSync(SQL_PATH, generateSql(cases));

  it("covers the 29th to the 31st, February and a leap year", () => {
    const cycle = (day: number, month: string) => cases.cycle.find((c) => c.day === day && c.month === month)?.expected;
    expect(cycle(31, "2027-04-01")).toBe("2027-04-30");
    expect(cycle(29, "2027-02-01")).toBe("2027-02-28");
    expect(cycle(29, "2028-02-01")).toBe("2028-02-29");
    expect(cycle(31, "2028-02-01")).toBe("2028-02-29");
    const due = (statementDate: string, dueDay: number) => cases.due.find((c) => c.statementDate === statementDate && c.dueDay === dueDay)?.expected;
    expect(due("2027-01-31", 30)).toBe("2027-02-28");
    expect(due("2028-01-31", 30)).toBe("2028-02-29");
    expect(due("2027-12-31", 1)).toBe("2028-01-01");
    expect(due("2027-10-28", 15)).toBe("2027-11-15"); // entered after that month's due day
  });

  it("the pgTAP file is up to date (run `npm run fixtures:cards`)", () => {
    expect(readFileSync(SQL_PATH, "utf8")).toBe(generateSql(cases));
  });
});
