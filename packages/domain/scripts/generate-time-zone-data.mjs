// Generates src/time-zone-data.ts: each IANA zone's UTC offset and its changes (DST and rule
// changes) from 2020 to 2050, read from this Node's ICU. Hermes on iOS cannot be trusted to
// read a time zone through Intl, so mobile turns an instant into local time from this table.
// Zones with identical offsets share one entry. Re-run when Node's tzdata changes; the
// parity test (src/time-zone.test.ts) compares the table with Intl in CI.
// Run with: node packages/domain/scripts/generate-time-zone-data.mjs
import { readFileSync, writeFileSync } from "node:fs";

export const FIRST_YEAR = 2020;
export const LAST_YEAR = 2050;

// Current names for ICU's legacy ones (Asia/Calcutta → Asia/Kolkata), from packages/schemas.
const regions = readFileSync(new URL("../../schemas/src/regions.ts", import.meta.url), "utf8");
const aliasBlock = regions.slice(regions.indexOf("LEGACY_TIME_ZONE_ALIASES"), regions.indexOf("};"));
const aliases = [...aliasBlock.matchAll(/"([^"]+)":\s*"([^"]+)"/g)].map((m) => [m[1], m[2]]);

const zones = [...new Set([...Intl.supportedValuesOf("timeZone"), "UTC", ...aliases.flat()])].sort();

const formatters = new Map();
/** UTC offset in minutes at an instant (ms), as ICU reports it. */
function offsetAt(zone, ms) {
  let f = formatters.get(zone);
  if (!f) {
    f = new Intl.DateTimeFormat("en-US", { timeZone: zone, timeZoneName: "longOffset" });
    formatters.set(zone, f);
  }
  const name = f.formatToParts(ms).find((p) => p.type === "timeZoneName").value;
  const m = /^GMT(?:([+-])(\d{2}):(\d{2}))?$/.exec(name);
  if (!m) throw new Error(`Unexpected offset "${name}" for ${zone}`);
  return m[1] ? (m[1] === "-" ? -1 : 1) * (Number(m[2]) * 60 + Number(m[3])) : 0;
}

const MINUTE = 60_000;
const DAY = 86_400_000;
const start = Date.UTC(FIRST_YEAR, 0, 1);
const end = Date.UTC(LAST_YEAR + 1, 0, 1);

// Entry format: "<offset at start>" then ";<minutes since the previous change, base 36>,<new offset>"
// for each change. The first change counts from the start of FIRST_YEAR.
function encode(zone) {
  let offset = offsetAt(zone, start);
  let out = String(offset);
  let previous = start;
  for (let t = start + DAY; t <= end; t += DAY) {
    const next = offsetAt(zone, t);
    if (next === offset) continue;
    let lo = t - DAY;
    let hi = t;
    while (hi - lo > MINUTE) {
      const mid = lo + Math.floor((hi - lo) / (2 * MINUTE)) * MINUTE;
      if (offsetAt(zone, mid) === offset) lo = mid;
      else hi = mid;
    }
    out += `;${((hi - previous) / MINUTE).toString(36)},${next}`;
    previous = hi;
    offset = next;
  }
  return out;
}

const entries = [];
const entryIndex = new Map();
const zoneIndex = {};
for (const zone of zones) {
  const entry = encode(zone);
  if (!entryIndex.has(entry)) {
    entryIndex.set(entry, entries.length);
    entries.push(entry);
  }
  zoneIndex[zone] = entryIndex.get(entry);
}

const out = `// Generated by packages/domain/scripts/generate-time-zone-data.mjs (Node ${process.version}, ICU ${process.versions.icu}, tzdata ${process.versions.tz}).
// Do not edit by hand; re-run the script to refresh.

/** Years the table covers exactly; others are read from a year 28 years away (same weekdays). */
export const TIME_ZONE_FIRST_YEAR = ${FIRST_YEAR};
export const TIME_ZONE_LAST_YEAR = ${LAST_YEAR};

/**
 * Offset entries: "<UTC offset in minutes on 1 January ${FIRST_YEAR}>", then for each change
 * ";<minutes since the previous change (from 1 January ${FIRST_YEAR} for the first), base 36>,<new offset>".
 */
export const TIME_ZONE_ENTRIES: readonly string[] = ${JSON.stringify(entries, null, 2)};

/** IANA zone (current and legacy names) → index in TIME_ZONE_ENTRIES. */
export const TIME_ZONE_INDEX: Readonly<Record<string, number>> = ${JSON.stringify(zoneIndex, null, 2)};
`;

writeFileSync(new URL("../src/time-zone-data.ts", import.meta.url), out);
console.warn(`time-zone-data.ts: ${zones.length} zones, ${entries.length} entries, ${out.length} bytes`);
