import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { addDays } from "./dates";
import { type Frequency, type Schedule, isOccurrence } from "./recurrence";

// Parity fixture: the same occurrence cases, with the answers from this package, checked
// here and by pgTAP against the database copy (public.recurring_is_occurrence).
// Regenerate both files after changing recurrence.ts: `npm run fixtures:recurrence`.

const JSON_PATH = fileURLToPath(new URL("./recurrence-parity.json", import.meta.url));
const SQL_PATH = fileURLToPath(new URL("../../../supabase/tests/database/recurrence_parity.test.sql", import.meta.url));

type Case = { frequency: Frequency; start: string; end: string | null; date: string; expected: boolean };

const SCHEDULES: (Schedule & { span: number })[] = [
  // Day 29/30/31 starts, crossing short months and the 2028 leap year (span in months).
  { frequency: "monthly", startDate: "2026-01-31", endDate: null, span: 28 },
  { frequency: "monthly", startDate: "2026-01-30", endDate: null, span: 28 },
  { frequency: "monthly", startDate: "2026-01-29", endDate: null, span: 28 },
  { frequency: "quarterly", startDate: "2026-11-30", endDate: "2027-11-30", span: 15 },
  { frequency: "yearly", startDate: "2026-03-15", endDate: "2029-03-15", span: 48 },
  { frequency: "yearly", startDate: "2028-02-29", endDate: null, span: 72 },
  { frequency: "weekly", startDate: "2026-12-28", endDate: "2027-02-15", span: 3 },
];

const isValid = (y: number, m: number, d: number) => new Date(Date.UTC(y, m - 1, d)).getUTCDate() === d;
const iso = (y: number, m: number, d: number) => `${String(y).padStart(4, "0")}-${String(m).padStart(2, "0")}-${String(d).padStart(2, "0")}`;

/** Dates around every boundary: before the start, month ends and starts, after the end. */
function datesFor(s: (typeof SCHEDULES)[number]): string[] {
  const dates = new Set<string>([addDays(s.startDate, -1), s.startDate]);
  if (s.endDate) [addDays(s.endDate, -1), s.endDate, addDays(s.endDate, 1)].forEach((d) => dates.add(d));
  if (s.frequency === "weekly") {
    for (let d = addDays(s.startDate, -3); d <= addDays(s.endDate ?? s.startDate, 10); d = addDays(d, 1)) dates.add(d);
  } else {
    const [y0, m0] = s.startDate.split("-").map(Number) as [number, number];
    for (let k = -1; k <= s.span; k++) {
      const index = y0 * 12 + (m0 - 1) + k;
      const y = Math.floor(index / 12);
      const m = (index % 12) + 1;
      for (const d of [1, 2, 14, 15, 16, 27, 28, 29, 30, 31]) if (isValid(y, m, d)) dates.add(iso(y, m, d));
    }
  }
  return [...dates].sort();
}

function generateCases(): Case[] {
  return SCHEDULES.flatMap((s) =>
    datesFor(s).map((date) => ({ frequency: s.frequency, start: s.startDate, end: s.endDate, date, expected: isOccurrence(s, date) }))
  );
}

function generateSql(cases: Case[]): string {
  const rows = cases
    .map((c, i) => {
      const end = c.end ? `date '${c.end}'` : "null::date";
      const first = i === 0;
      return `  ('${c.frequency}'${first ? "::text" : ""}, date '${c.start}', ${end}, date '${c.date}', ${c.expected})`;
    })
    .join(",\n");
  const mismatches = `$$ select c.frequency, c.start_date, c.end_date, c.on_date, c.expected
     from parity as c
     where public.recurring_is_occurrence(c.frequency, c.start_date, c.end_date, c.on_date) is distinct from c.expected $$`;
  return `-- GENERATED by packages/domain/src/recurrence-parity.test.ts from packages/domain/src/recurrence.ts.
-- Do not edit: run \`npm run fixtures:recurrence\`. ${cases.length} cases.
-- The database copy of the occurrence rule (public.recurring_is_occurrence, migration
-- 20261024120000) must give the same answer for every case, in any session time zone.
begin;
create extension if not exists pgtap with schema extensions;

select plan(3);

create temporary table parity (frequency text, start_date date, end_date date, on_date date, expected boolean) on commit drop;
insert into parity values
${rows};

select is_empty(${mismatches},
  'recurring_is_occurrence matches packages/domain (${cases.length} cases)');

set local timezone = 'Pacific/Kiritimati';
select is_empty(${mismatches},
  'and with the session time zone at UTC+14');

set local timezone = 'Pacific/Pago_Pago';
select is_empty(${mismatches},
  'and with the session time zone at UTC-11');

select * from finish();
rollback;
`;
}

const write = process.env.RECURRENCE_FIXTURE === "write";

describe("recurrence parity fixture", () => {
  const cases = generateCases();
  if (write) {
    writeFileSync(JSON_PATH, `${JSON.stringify(cases, null, 2)}\n`);
    writeFileSync(SQL_PATH, generateSql(cases));
  }
  const fixture = JSON.parse(readFileSync(JSON_PATH, "utf8")) as Case[];

  it("covers day 29/30/31 starts, leap years, weekly, quarterly, yearly, before start and after end", () => {
    expect(fixture.length).toBeGreaterThan(400);
    expect(fixture.some((c) => c.date === "2028-02-29" && c.expected)).toBe(true); // leap day
    expect(fixture.some((c) => c.start === "2026-01-31" && c.date === "2026-02-28" && c.expected)).toBe(true);
    expect(fixture.some((c) => c.start === "2028-02-29" && c.date === "2029-02-28" && c.expected)).toBe(true);
    expect(fixture.some((c) => c.end && c.date > c.end && !c.expected)).toBe(true); // after end
    expect(fixture.some((c) => c.date < c.start && !c.expected)).toBe(true); // before start
  });

  it("packages/domain gives the fixture's answer for every case", () => {
    const wrong = fixture.filter((c) => isOccurrence({ frequency: c.frequency, startDate: c.start, endDate: c.end }, c.date) !== c.expected);
    expect(wrong).toEqual([]);
  });

  it("the fixture and the pgTAP file are up to date (run `npm run fixtures:recurrence`)", () => {
    expect(fixture).toEqual(cases);
    expect(readFileSync(SQL_PATH, "utf8")).toBe(generateSql(fixture));
  });
});
