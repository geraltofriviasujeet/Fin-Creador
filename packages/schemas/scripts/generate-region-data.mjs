// Generates src/region-data.ts: country, currency and time-zone lists with English (India)
// display names. Mobile (Hermes) has no Intl.supportedValuesOf or Intl.DisplayNames, so
// both clients read these static lists instead of the runtime's.
// Run with: node packages/schemas/scripts/generate-region-data.mjs
import { writeFileSync } from "node:fs";

const LOCALE = "en-IN";

// ISO 3166-1 alpha-2 codes (officially assigned).
const COUNTRY_CODES = (
  "AD AE AF AG AI AL AM AO AQ AR AS AT AU AW AX AZ BA BB BD BE BF BG BH BI BJ BL BM BN BO BQ " +
  "BR BS BT BV BW BY BZ CA CC CD CF CG CH CI CK CL CM CN CO CR CU CV CW CX CY CZ DE DJ DK DM " +
  "DO DZ EC EE EG EH ER ES ET FI FJ FK FM FO FR GA GB GD GE GF GG GH GI GL GM GN GP GQ GR GS " +
  "GT GU GW GY HK HM HN HR HT HU ID IE IL IM IN IO IQ IR IS IT JE JM JO JP KE KG KH KI KM KN " +
  "KP KR KW KY KZ LA LB LC LI LK LR LS LT LU LV LY MA MC MD ME MF MG MH MK ML MM MN MO MP MQ " +
  "MR MS MT MU MV MW MX MY MZ NA NC NE NF NG NI NL NO NP NR NU NZ OM PA PE PF PG PH PK PL PM " +
  "PN PR PS PT PW PY QA RE RO RS RU RW SA SB SC SD SE SG SH SI SJ SK SL SM SN SO SR SS ST SV " +
  "SX SY SZ TC TD TF TG TH TJ TK TL TM TN TO TR TT TV TW TZ UA UG UM US UY UZ VA VC VE VG VI " +
  "VN VU WF WS YE YT ZA ZM ZW"
).split(" ");

const regionNames = new Intl.DisplayNames([LOCALE], { type: "region" });
const currencyNames = new Intl.DisplayNames([LOCALE], { type: "currency" });

// Sorted by name here so clients need no locale-aware collation at runtime.
const countries = Object.fromEntries(
  COUNTRY_CODES.map((code) => [code, regionNames.of(code) ?? code]).sort(([, a], [, b]) => a.localeCompare(b, LOCALE))
);
const currencies = Object.fromEntries(
  [...new Set([...Intl.supportedValuesOf("currency"), "INR"])]
    .sort()
    .map((code) => [code, currencyNames.of(code) ?? code])
);
// Raw runtime names; regions.ts maps legacy aliases (Asia/Calcutta) to current ones.
const timeZones = [...new Set([...Intl.supportedValuesOf("timeZone"), "UTC"])].sort();

const json = (value) => JSON.stringify(value, null, 2);

const out = `// Generated by packages/schemas/scripts/generate-region-data.mjs (Node ${process.version}, ICU ${process.versions.icu}).
// Do not edit by hand; re-run the script to refresh.

/** ISO 3166-1 alpha-2 code → English (India) name, in name order. */
export const COUNTRY_NAMES: Readonly<Record<string, string>> = ${json(countries)};

/** ISO 4217 code → English (India) name. */
export const CURRENCY_NAMES: Readonly<Record<string, string>> = ${json(currencies)};

/** IANA time zones as reported by ICU (may include legacy aliases). */
export const RAW_TIME_ZONES: readonly string[] = ${json(timeZones)};
`;

writeFileSync(new URL("../src/region-data.ts", import.meta.url), out);
console.warn(
  `region-data.ts: ${COUNTRY_CODES.length} countries, ${Object.keys(currencies).length} currencies, ${timeZones.length} time zones`
);
