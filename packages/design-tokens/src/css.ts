// Converts tokens into CSS custom properties. Used by scripts/generate-css.ts
// (writes tokens.css) and by the sync test. Not part of the runtime API.
import { colors, fontSize, layout, letterSpacing, radius, shadow } from "./index.ts";

const kebab = (key: string) => key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

export function toCssVariables(): string {
  const lines: string[] = [];
  const add = (name: string, value: string) => lines.push(`  --fc-${name}: ${value};`);

  for (const [k, v] of Object.entries(colors)) add(`color-${kebab(k)}`, v);
  for (const [k, v] of Object.entries(radius)) add(`radius-${kebab(k)}`, `${v}px`);
  for (const [k, v] of Object.entries(shadow)) add(`shadow-${kebab(k)}`, v);
  for (const [k, v] of Object.entries(fontSize)) add(`text-${k}`, `${v / 16}rem`);
  for (const [k, v] of Object.entries(letterSpacing)) add(`tracking-${kebab(k)}`, `${v}px`);
  for (const [k, v] of Object.entries(layout)) add(`layout-${kebab(k)}`, `${v}px`);

  return [
    "/* GENERATED by packages/design-tokens/scripts/generate-css.ts — do not edit. */",
    "/* Source: packages/design-tokens/src/index.ts. Run `npm run tokens` to update. */",
    ":root {",
    ...lines,
    "}",
    "",
  ].join("\n");
}
